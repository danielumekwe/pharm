// Self-service registration of a new pharmacy (tenant).
//
// 1. Platform records, in one transaction: the tenant (with the caller's registration key) and its trial
//    subscription on the chosen plan.
// 2. The pharmacy's own records, in its own tenant transaction: the owner account (global user + Super
//    Admin membership), the first outlet, default settings and the default role matrix, plus an audit entry.
// 3. A verification email to the owner (best effort: registration does not fail if email is down).
// If step 2 fails, step 1 is undone. A retry with the same registration key returns the first result
// instead of creating a second pharmacy.
import { randomBytes } from "node:crypto";
import { z } from "zod";

import { platformQuery, withDatabaseTransaction } from "@/lib/db/database";
import { outlets, users } from "@/lib/data";
import { newId } from "@/lib/erp/ids";
import { DomainError, recordAudit } from "@/lib/erp/services";
import { getStore } from "@/lib/erp/store";
import { nextStaffId } from "@/lib/erp/users";
import { hashPassword } from "@/lib/password";
import { DEFAULT_ROLE_PERMISSIONS, setRoleMatrix } from "@/lib/rbac";
import { sendVerificationEmail } from "@/lib/saas/account-email";
import { emailTaken } from "@/lib/saas/identity";
import { runInTenant } from "@/lib/saas/tenant";

export const COUNTRIES = { NG: "Nigeria", GH: "Ghana", KE: "Kenya", ZA: "South Africa", GB: "United Kingdom", US: "United States" } as const;
export const CURRENCIES = ["NGN", "GHS", "KES", "ZAR", "GBP", "USD", "EUR"] as const;
export const NIGERIAN_STATES = [
  "Abia", "Adamawa", "Akwa Ibom", "Anambra", "Bauchi", "Bayelsa", "Benue", "Borno", "Cross River", "Delta", "Ebonyi", "Edo", "Ekiti", "Enugu",
  "FCT Abuja", "Gombe", "Imo", "Jigawa", "Kaduna", "Kano", "Katsina", "Kebbi", "Kogi", "Kwara", "Lagos", "Nasarawa", "Niger", "Ogun", "Ondo",
  "Osun", "Oyo", "Plateau", "Rivers", "Sokoto", "Taraba", "Yobe", "Zamfara",
] as const;

const phone = z.string().trim().refine((value) => /^\+?[\d\s()-]+$/.test(value) && value.replace(/\D/g, "").length >= 10 && value.replace(/\D/g, "").length <= 14, "Enter a valid phone number (10–14 digits).");
const email = z.string().trim().toLowerCase().max(160).email("Enter a valid email address.");

/** Account passwords: at least 8 characters with a letter and a number. */
export const strongPassword = z.string().min(8, "Use at least 8 characters.").max(128).refine((value) => /[A-Za-z]/.test(value) && /\d/.test(value), "Use letters and at least one number.");

export const registrationSchema = z.object({
  /** Generated by the form once per registration attempt; makes retries safe. */
  requestId: z.string().uuid(),
  businessName: z.string().trim().min(2, "Enter the pharmacy's name.").max(120),
  businessEmail: email,
  businessPhone: phone,
  ownerName: z.string().trim().min(3, "Enter the owner's full name.").max(120),
  ownerEmail: email,
  ownerPhone: phone,
  address: z.string().trim().min(5, "Enter the business address.").max(240),
  country: z.enum(Object.keys(COUNTRIES) as [keyof typeof COUNTRIES, ...Array<keyof typeof COUNTRIES>]),
  state: z.string().trim().min(2, "Enter the state or region.").max(60),
  currency: z.enum(CURRENCIES),
  timeZone: z.string().refine((value) => Intl.supportedValuesOf("timeZone").includes(value) || value === "UTC", "Choose a valid time zone."),
  password: strongPassword,
  planId: z.string().min(1).max(40),
  billingCycle: z.enum(["MONTHLY", "ANNUAL"]).default("MONTHLY"),
}).refine((input) => input.country !== "NG" || (NIGERIAN_STATES as readonly string[]).includes(input.state), { path: ["state"], message: "Choose a Nigerian state." });

export type RegistrationInput = z.infer<typeof registrationSchema>;
export type PublicPlan = { id: string; name: string; description: string; monthlyPrice: number | null; annualPrice: number | null; currency: string; trialDays: number };

/** Plans offered on the registration page (active and public), cheapest first. */
export async function publicPlans(): Promise<PublicPlan[]> {
  const rows = await platformQuery<Array<{ id: string; name: string; description: string; monthly_price: string | null; annual_price: string | null; currency: string; trial_days: number }>>((query) =>
    query(`SELECT id, name, description, monthly_price, annual_price, currency, trial_days FROM plans WHERE is_active AND is_public ORDER BY sort_order, name`),
  );
  return rows.map((row) => ({
    id: row.id,
    name: row.name,
    description: row.description,
    monthlyPrice: row.monthly_price === null ? null : Number(row.monthly_price),
    annualPrice: row.annual_price === null ? null : Number(row.annual_price),
    currency: row.currency,
    trialDays: Number(row.trial_days),
  }));
}

function slugBase(name: string) {
  return name.toLowerCase().normalize("NFKD").replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "").slice(0, 40) || "pharmacy";
}

export type RegistrationResult = { tenantId: string; ownerEmail: string; created: boolean; verificationEmail: "SENT" | "SKIPPED" | "FAILED" | "NOT_SENT" };

export async function registerPharmacy(input: RegistrationInput): Promise<RegistrationResult> {
  // A retry of the same registration: return what the first attempt created.
  const existing = await tenantForKey(input.requestId);
  if (existing) {
    if (existing.ownerEmail !== input.ownerEmail) throw new DomainError("This registration was already submitted with different details. Reload the page to start again.", 409);
    return { tenantId: existing.tenantId, ownerEmail: input.ownerEmail, created: false, verificationEmail: "NOT_SENT" };
  }
  if (await emailTaken(input.ownerEmail)) throw new DomainError("An account with this email already exists. Sign in instead, or use another email.", 409);

  const plans = await publicPlans();
  const plan = plans.find((entry) => entry.id === input.planId);
  if (!plan) throw new DomainError("Choose one of the plans offered.", 400);

  const tenantId = `t-${randomBytes(5).toString("hex")}`;
  try {
    await platformQuery(async (query) => {
      const taken = new Set((await query<{ slug: string }>(`SELECT slug FROM tenants WHERE slug LIKE $1`, [`${slugBase(input.businessName)}%`])).map((row) => row.slug));
      const base = slugBase(input.businessName);
      let slug = base;
      for (let index = 2; taken.has(slug); index += 1) slug = `${base}-${index}`;
      await query(
        `INSERT INTO tenants (id, slug, name, status, business_email, business_phone, address, country, state, currency, time_zone, registration_key)
         VALUES ($1, $2, $3, 'ACTIVE', $4, $5, $6, $7, $8, $9, $10, $11)`,
        [tenantId, slug, input.businessName, input.businessEmail, input.businessPhone, input.address, input.country, input.state, input.currency, input.timeZone, input.requestId],
      );
      await query(
        `INSERT INTO subscriptions (id, tenant_id, plan_id, status, billing_cycle, trial_ends_at) VALUES ($1, $2, $3, 'TRIAL', $4, $5)`,
        [`sub-${tenantId}`, tenantId, plan.id, input.billingCycle, new Date(Date.now() + plan.trialDays * 86_400_000)],
      );
    });
  } catch (error) {
    // Two submissions of the same form at once: the second finds the first's pharmacy.
    if (isUniqueViolation(error)) {
      const raced = await tenantForKey(input.requestId);
      if (raced && raced.ownerEmail === input.ownerEmail) return { tenantId: raced.tenantId, ownerEmail: input.ownerEmail, created: false, verificationEmail: "NOT_SENT" };
    }
    throw error;
  }

  let owner: { id: string; name: string; email: string };
  try {
    owner = await runInTenant(tenantId, () => withDatabaseTransaction(() => setUpPharmacy(input)));
  } catch (error) {
    // Undo the platform records so the same details can be submitted again.
    await platformQuery((query) => query(`DELETE FROM tenants WHERE id = $1`, [tenantId])).catch((cleanup) => console.error("[registration] cleanup failed", cleanup));
    throw error;
  }

  let verificationEmail: RegistrationResult["verificationEmail"] = "FAILED";
  try {
    verificationEmail = (await sendVerificationEmail(owner, input.businessName)).status;
  } catch (error) {
    console.error("[registration] verification email failed", error);
  }
  return { tenantId, ownerEmail: input.ownerEmail, created: true, verificationEmail };
}

/** Runs inside the new pharmacy's transaction: its working set starts empty. */
function setUpPharmacy(input: RegistrationInput) {
  const now = new Date().toISOString();
  const outletId = newId("outlet", 1);
  outlets.push({
    id: outletId,
    name: `${input.businessName} – Main`,
    code: "MAIN",
    manager: input.ownerName,
    address: input.address,
    phone: input.businessPhone,
    type: "RETAIL",
    status: "ACTIVE",
    stockValue: 0,
    sales: 0,
  });
  const owner = {
    id: newId("user", Date.now()),
    name: input.ownerName,
    email: input.ownerEmail,
    phone: input.ownerPhone,
    passwordHash: hashPassword(input.password),
    role: "SUPER_ADMIN" as const,
    outletId: null,
    outletIds: [],
    status: "ACTIVE" as const,
    staffId: nextStaffId(),
    createdAt: now,
  };
  users.push(owner);
  getStore().settings.businessName = input.businessName;
  setRoleMatrix(structuredClone(DEFAULT_ROLE_PERMISSIONS)); // saved as this pharmacy's own, editable matrix
  recordAudit(owner, {
    action: "tenant.registered",
    entity: "Tenant",
    entityId: outletId,
    summary: `${input.ownerName} registered ${input.businessName} (${input.state}, ${COUNTRIES[input.country]}) on the ${input.planId} plan with ${input.billingCycle.toLowerCase()} billing; first outlet created`,
  });
  return { id: owner.id, name: owner.name, email: owner.email };
}

async function tenantForKey(requestId: string) {
  const rows = await platformQuery<Array<{ tenant_id: string; owner_email: string | null }>>((query) =>
    query(
      `SELECT t.id AS tenant_id,
              (SELECT u.email FROM tenant_memberships m JOIN users u ON u.id = m.user_id WHERE m.tenant_id = t.id AND m.role = 'SUPER_ADMIN' ORDER BY m.created_at LIMIT 1) AS owner_email
       FROM tenants t WHERE t.registration_key = $1`,
      [requestId],
    ),
  );
  const row = rows[0];
  return row ? { tenantId: row.tenant_id, ownerEmail: row.owner_email ?? "" } : null;
}

function isUniqueViolation(error: unknown) {
  return Boolean(error && typeof error === "object" && "code" in error && error.code === "P2010" && /\b23505\b/.test(String((error as { message?: unknown }).message)));
}
